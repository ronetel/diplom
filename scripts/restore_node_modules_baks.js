const fs = require('fs');
const path = require('path');
const targetDir = path.resolve(__dirname, '..', 'backend', 'node_modules');
let restored = 0;

function walk(dir) {
  if (!fs.existsSync(dir)) return;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full);
    else if (e.isFile() && full.endsWith('.bak')) {
      const orig = full.slice(0, -4);
      try {
        fs.copyFileSync(full, orig);
        fs.unlinkSync(full);
        restored++;
        console.log('Restored:', orig);
      } catch (err) {
        console.error('Failed restore', full, err.message);
      }
    }
  }
}

walk(targetDir);
console.log('Done. Restored count:', restored);
